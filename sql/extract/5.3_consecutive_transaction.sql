/* 계좌별 연속거래여부  (수신/여신 계좌 한정, 선행 계좌연속거래마스터 마트 활용) */

SELECT 기준일자
     , 수신여신구분코드
     , 계약번호
     , 고객번호
     , 상품코드
     , 계좌상태코드
     , 연속거래일수
     , 연속거래여부
  FROM 계좌연속거래마스터
 WHERE 기준일자 = :기준변수일자
   -- AND 연속거래여부 = 'Y'    /* 30일 이상 연속거래 계좌만 추출 시 */
 ORDER BY 수신여신구분코드
        , 연속거래일수 DESC
;

/* 고객별 연속거래여부  (수신/여신 각각의 최대 연속거래 - 고객별상품실적현황 마트 활용) */

SELECT 기준일자
     , 고객번호
     , 고객유형코드
     , 수신_최대연속거래일수
     , 수신_최대연속거래여부
     , 여신_최대연속거래일수
     , 여신_최대연속거래여부
  FROM 고객별상품실적현황
 WHERE 기준일자 = :기준변수일자
   -- AND ( 수신_최대연속거래여부 = 'Y' OR 여신_최대연속거래여부 = 'Y' )   /* 연속거래 고객만 */
 ORDER BY 기준일자
        , 고객번호
;
