/* ============================================================
-- 기간별 계좌별 평균잔액 추출
-- 파라미터 : :시작일자 , :종료일자  (VARCHAR(8) 'YYYYMMDD')
-- 원천    : 일별계좌잔액 (dense 일별 잔액 마트, 종료일자까지 적재 선행)
-- ============================================================ */

SELECT 수신여신구분코드   /* 01:수신 / 02:여신 */
     , 계약번호
     , 고객번호
     , 상품코드
     , COUNT(*)                   AS 보유일수
     , ( TO_DATE(:종료일자,'YYYYMMDD') - TO_DATE(:시작일자,'YYYYMMDD') ) + 1 AS 기간일수
     , ROUND( AVG(일마감잔액), 2 )  AS 보유기간평잔
     , ROUND( SUM(일마감잔액) / ( ( TO_DATE(:종료일자,'YYYYMMDD') - TO_DATE(:시작일자,'YYYYMMDD') ) + 1 )
            , 2 )                 AS 고정기간평잔   /* 해지계좌 포함 및 기간의 기여도 */
     , MIN(일마감잔액)              AS 기간최소잔액
     , MAX(일마감잔액)              AS 기간최대잔액
  FROM 일별계좌잔액
 WHERE 기준일자 BETWEEN :시작일자 AND :종료일자
 GROUP BY 수신여신구분코드
        , 계약번호
        , 고객번호
        , 상품코드
 ORDER BY 수신여신구분코드
        , 계약번호
;

/* ============================================================
-- 기간별 고객별 평균잔액 추출 (수신/여신)
-- 파라미터 : :시작일자 , :종료일자  (VARCHAR(8) 'YYYYMMDD')
-- 원천    : 일별계좌잔액 (dense 일별 잔액 마트, 종료일자까지 적재 선행)
-- ============================================================ */

WITH 고객일별잔액 AS (

SELECT 수신여신구분코드
     , 고객번호
     , 기준일자
     , SUM(일마감잔액)  AS 고객일별잔액합계
  FROM 일별계좌잔액
 WHERE 기준일자 BETWEEN :시작일자 AND :종료일자
 GROUP BY 수신여신구분코드
         , 고객번호
         , 기준일자

)
, 고객일별평잔 AS (

SELECT 수신여신구분코드
     , 고객번호
     , COUNT(*)                         AS 보유일수
     , ( TO_DATE(:종료일자,'YYYYMMDD') - TO_DATE(:시작일자,'YYYYMMDD') ) + 1 AS 기간일수
     , ROUND( AVG(고객일별잔액합계), 2 )   AS 보유기간평잔
     , ROUND( SUM(고객일별잔액합계) / ( ( TO_DATE(:종료일자,'YYYYMMDD') - TO_DATE(:시작일자,'YYYYMMDD') ) + 1 )
            , 2 )                       AS 고정기간평잔   /* 해지계좌 포함 및 기간의 기여도 */
     , MIN(고객일별잔액합계)              AS 기간최소고객일잔액합계
     , MAX(고객일별잔액합계)              AS 기간최대고객일잔액합계
  FROM 고객일별잔액
 GROUP BY 수신여신구분코드
        , 고객번호

)
SELECT 고객번호
     , MAX(CASE WHEN 수신여신구분코드 = '01' THEN 보유기간평잔 ELSE 0 END)  AS 고객_수신_보유기간평잔
     , MAX(CASE WHEN 수신여신구분코드 = '02' THEN 보유기간평잔 ELSE 0 END)  AS 고객_여신_보유기간평잔
     , MAX(CASE WHEN 수신여신구분코드 = '01' THEN 고정기간평잔 ELSE 0 END)  AS 고객_수신_고정기간평잔
     , MAX(CASE WHEN 수신여신구분코드 = '02' THEN 고정기간평잔 ELSE 0 END)  AS 고객_여신_고정기간평잔
  FROM 고객일별평잔
 GROUP BY 고객번호
 ORDER BY 고객번호
;
